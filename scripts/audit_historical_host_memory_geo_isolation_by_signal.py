def file_sha256(path:Path)->str:
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for b in iter(lambda:f.read(1<<20),b''):
            h.update(b)
    return h.hexdigest()


def rank_average(x)->np.ndarray:
    """Average tied ranks / species sample size, exactly one sample per site."""
    x=np.asarray(x,dtype=float)
    if x.ndim!=1 or not len(x) or not np.isfinite(x).all():
        raise ValueError('nonfinite or empty nearest-neighbor distance series')
    return rankdata(x,method='average')/len(x)


def stratified_geographic_fragility(species, deletion, localities, edges):
    """Aggregate nearest-neighbor ranks separately in frozen signal quartiles."""
    sr={'species','edges','localities','standardized_beta','semipartial_correlation',
        'unique_fraction','unscaled_slope','locality_deletions_defined',
        'locality_deletions_undefined','locality_deletions_reversing_sign'}
    dr={'species','locality_index','status','slope'}
    lr={'species','locality_index','x_km','y_km','z_km'}
    er={'species','edge_index','node_left','node_right'}
    for tbl,req,label in ((species,sr,'species'),(deletion,dr,'site'),
                          (localities,lr,'locality'),(edges,er,'edge')):
        if not req.issubset(tbl.columns):
            raise ValueError('missing required frozen '+label+' columns')
    if species.species.duplicated().any():
        raise ValueError('duplicate survivor species')
    if species.standardized_beta.isna().sum() < 0:
        raise ValueError('impossible standardization flags')
    finite=species[species.standardized_beta.notna()].copy()
    if not len(finite) >= 4:
        raise ValueError('insufficient defined species for frozen quartile comparison')
    if np.any(finite.semipartial_correlation.isna()) or not np.isfinite(finite.semipartial_correlation).all():
        raise ValueError('semipartial coefficients not defined for eligible species')
    if not np.allclose(finite.semipartial_correlation.to_numpy(dtype=float),
                       finite.standardized_beta.to_numpy(dtype=float) *
                       np.sqrt(finite.unique_fraction.to_numpy(dtype=float)),atol=1e-10,rtol=1e-10):
        raise ValueError('frozen beta and semipartial identity mismatch')
    if (species.loc[species.standardized_beta.isna(),'semipartial_correlation'].notna().any()
        or np.any(species.loc[species.standardized_beta.isna(),'unscaled_slope']!=0)):
        raise ValueError('invariant COI species cannot be assigned artificial signal')
    finite['quartile']=pd.qcut(finite.semipartial_correlation.abs(),4,labels=[1,2,3,4],duplicates='raise').astype(int)
    by_sp=species.set_index('species')
    q_by_sp=dict(zip(finite.species,finite.quartile))
    selected=set(species.species)
    if (set(deletion.species)!=selected or set(q_by_sp)!=selected-set(species.loc[species.standardized_beta.isna(),'species'])):
        raise ValueError('deleted-site species differ from frozen 259 species')
    lsub=localities.loc[localities.species.isin(selected)]
    esub=edges.loc[edges.species.isin(selected)]
    if set(lsub.species)!=selected or set(esub.species)!=selected:
        raise ValueError('frozen geographic source is missing one or more species')
    if (lsub.duplicated(['species','locality_index']).any()
        or esub.duplicated(['species','edge_index']).any()
        or deletion.duplicated(['species','locality_index']).any()):
        raise ValueError('duplicate original frozen locality/edge/deletion identity')

    stats={j:{'n':0,'yes':[],'no':[],'paired':[],'flipping_species':0,'defined':0,'undefined':0}
           for j in (1,2,3,4)}
    total_original_edges=0
    attempted=defined_total=undefined_total=all_flips=0
    invariant=0
    for name,row in by_sp.iterrows():
        n=int(row.localities);k=int(row.edges)
        l=lsub.loc[lsub.species==name].sort_values('locality_index')
        e=esub.loc[esub.species==name].sort_values('edge_index')
        d=deletion.loc[deletion.species==name].sort_values('locality_index')
        if len(l)!=n or l.locality_index.tolist()!=list(range(n)):
            raise ValueError('frozen locality index mismatch')
        if len(d)!=n or d.locality_index.tolist()!=list(range(n)):
            raise ValueError('frozen deleted-locality index mismatch')
        if len(e)!=k or e.edge_index.tolist()!=list(range(k)):
            raise ValueError('original frozen edge identity/count mismatch')
        nodes=e[['node_left','node_right']].to_numpy(dtype=int)
        if np.any(nodes<0) or np.any(nodes>=n):
            raise ValueError('edge references nonexistent frozen locality')
        if np.any(nodes[:,0]==nodes[:,1]) or len(np.unique(np.sort(nodes,axis=1),axis=0))!=k:
            raise ValueError('duplicate or self frozen geographical edges')
        coords=l[['x_km','y_km','z_km']].to_numpy(dtype=float)
        if coords.shape!=(n,3) or not np.isfinite(coords).all():
            raise ValueError('invalid frozen ECEF source')
        distances=np.linalg.norm(coords[:,None,:]-coords[None,:,:],axis=2)
        np.fill_diagonal(distances,np.inf)
        rank=rank_average(distances.min(axis=1))
        init=float(row.unscaled_slope)
        if not np.isfinite(init):
            raise ValueError('nonfinite original exposed slope')
        q=q_by_sp.get(name)
        ys=[];ns=[]
        for j,v in enumerate(d.itertuples(index=False)):
            if v.status=='undefined':
                if not pd.isna(v.slope):
                    raise ValueError('undefined site deletion must not carry a fabricated coefficient')
                undefined_total+=1
                if q is not None:stats[q]['undefined']+=1
                continue
            if v.status!='defined' or not np.isfinite(v.slope):
                raise ValueError('unknown or nonfinite original site deletion status')
            defined_total+=1
            if q is not None:stats[q]['defined']+=1
            flip=init!=0 and np.sign(v.slope)==-np.sign(init)
            if flip:all_flips+=1
            if q is not None:
                (ys if flip else ns).append(float(rank[j]))
            elif abs(float(v.slope))>1e-13:
                raise ValueError('invariant COI baseline developed a nonzero omission coefficient')
        if len(ys)!=int(row.locality_deletions_reversing_sign):
            raise ValueError('source reversal count mismatch')
        if int(row.locality_deletions_defined)!=int((d.status=='defined').sum()) or int(row.locality_deletions_undefined)!=int((d.status=='undefined').sum()):
            raise ValueError('original locality-deletion definability mismatch')
        attempted+=n
        total_original_edges+=k
        if q is None:invariant+=1
        else:
            S=stats[q];S['n']+=1;S['yes'].extend(ys);S['no'].extend(ns)
            S['flipping_species']+=int(len(ys)>0)
            if ys and ns:S['paired'].append(float(np.mean(ys)-np.mean(ns)))
    out=[]
    for q,S in stats.items():
        out.append({
            'quartile':q,'species':S['n'],'species_with_any_reversal':S['flipping_species'],
            'flip_events':len(S['yes']),'nonflip_defined_events':len(S['no']),
            'defined_deletions':S['defined'],'undefined_deletions':S['undefined'],
            'mean_flip_nearest_rank':float(np.mean(S['yes'])) if S['yes'] else None,
            'mean_other_nearest_rank':float(np.mean(S['no'])) if S['no'] else None,
            'species_with_both_types':len(S['paired']),
            'paired_median_rank_difference':float(np.median(S['paired'])) if S['paired'] else None,
        })
    all_yes=[v for s in stats.values() for v in s['yes']]
    all_no=[v for s in stats.values() for v in s['no']]
    return {
        'schema':'ttf_hhm259_fragility_by_semipartial_and_sampling_isolation_v0.1',
        'status':'EXPLORATORY_POST_OUTCOME_SAMPLING_GEOGRAPHY',
        'original_confirmatory_status':'NOT_EVALUABLE_EMPIRICAL_RESPONSE',
        'n_frozen_survivors':len(species),'n_nonzero_defined':len(finite),
        'n_invariant':invariant,'frozen_original_edges':total_original_edges,
        'attempted_site_deletions':attempted,'defined_site_deletions':defined_total,
        'undefined_deletion_variants':undefined_total,
        'flip_event_total':all_flips,
        'overall_flip_site_nearest_neighbor_rank':float(np.mean(all_yes)) if all_yes else None,
        'overall_other_site_nearest_neighbor_rank':float(np.mean(all_no)) if all_no else None,
        'semipartial_quartile_geography':out,
        'method':'Nearest-neighbor ECEF chord distance rankdata-average divided by number of frozen original localities within each species; quartiles of abs(beta_standardized*sqrt(unique_host_history_fraction)) among 255 originally defined standardized responses. Previously exposed original locality deletion results only.',
        'no_public_species_names_or_per_site_results':True,
        'sampling_isolation_not_evidence_of_LGM_barrier':True,
        'not_an_independent_ecological_genetic_test':True,
        'original_panel_changed':False,'genetic_identity_reopened':False,
        'new_p_values':0,'new_hypothesis_tests':0,'confidence_intervals_computed':False,
    }


def main():
    p=argparse.ArgumentParser()
    for v in ('species_stability','site_deletions','frozen_localities','frozen_edges','original_empirical_terminal'):
        p.add_argument('--'+v.replace('_','-'),type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    args=p.parse_args()
    for name,digest in PINS.items():
        if file_sha256(getattr(args,name))!=digest:
            raise ValueError('frozen SHA256 mismatch: '+name)
    t=json.loads(args.original_empirical_terminal.read_text())
    if (t.get('status')!='NOT_EVALUABLE_EMPIRICAL_RESPONSE' or t.get('monte_carlo_p') is not None):
        raise ValueError('original consumed one-shot outcome was modified')
    result=stratified_geographic_fragility(
        pd.read_csv(args.species_stability),
        pd.read_csv(args.site_deletions),
        pd.read_csv(args.frozen_localities,float_precision='round_trip'),
        pd.read_csv(args.frozen_edges)
    )
    if (result['n_frozen_survivors'],result['n_nonzero_defined'],result['n_invariant'],
        result['frozen_original_edges'],result['attempted_site_deletions'],
        result['defined_site_deletions'],result['undefined_deletion_variants'],
        result['flip_event_total'])!=(259,255,4,20362,6374,6373,1,420):
        raise RuntimeError('original 259-species exposure counts changed')
    if (abs(result['overall_flip_site_nearest_neighbor_rank']-0.5722075791028662)>1e-11 or
        abs(result['overall_other_site_nearest_neighbor_rank']-0.5164893823783056)>1e-11):
        raise RuntimeError('published independent original nearest-neighbor rank audit differs')
    result['source_sha256']=PINS
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(result,indent=2,sort_keys=True)+'\n')
    print(json.dumps({'status':result['status'],'quartiles':result['semipartial_quartile_geography']}))

if __name__=='__main__':
    main()
